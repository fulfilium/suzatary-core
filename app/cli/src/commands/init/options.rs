//! The choices a deployment begins from, as the Markdown `AGENT.md` holds between its options
//! markers: a reading of `init`'s own argument tree, its value enums and the steps
//! [`Onboarding::steps`](super::Onboarding::steps) prints, never a second list of them. `suzatary init --options` prints
//! it, and a guard holds the committed file to it, so the guide and the verb cannot offer
//! different choices.

use std::fmt::Write as _;

use clap::{CommandFactory as _, ValueEnum};
use suzatary_core::cast::CAST;

use super::{FirstAccount, Flags, Provider, Reach};

/// The line before the generated text in `AGENT.md`.
pub const BEGIN: &str =
    "<!-- options: generated by `suzatary init --options`; edit the code, never this text -->";

/// The line after it.
pub const END: &str = "<!-- end of options -->";

/// How the steps are spelled: through the user repository's script, as the guide runs them.
const SCRIPT: &str = "./suzatary";

/// The flags `init` takes that choose nothing about the deployment.
const NOT_CHOICES: [&str; 3] = ["help", "force", "options"];

/// The options, from [`BEGIN`] to [`END`] inclusive, ending with a newline.
#[must_use]
pub fn markdown() -> String {
    let reach = Reach::Script(SCRIPT.to_owned());
    let mut out = format!("{BEGIN}\n\n");
    flags(&mut out);
    mail(&mut out, &reach);
    models(&mut out, &reach);
    connectors(&mut out);
    out.push_str(END);
    out.push('\n');
    out
}

/// Every flag `init` asks, with its own help.
fn flags(out: &mut String) {
    out.push_str("### Who, where, and who may come in\n\n");
    out.push_str("`init` asks for any of these it is not given, at a terminal.\n\n");
    out.push_str("| Flag | What it sets |\n|---|---|\n");
    let command = Flags::command();
    for arg in command.get_arguments() {
        let (Some(long), Some(help)) = (arg.get_long(), arg.get_help()) else {
            continue;
        };
        if NOT_CHOICES.contains(&long) {
            continue;
        }
        let _ = writeln!(out, "| `--{long}` | {} |", one_line(&help.to_string()));
    }
    out.push('\n');
}

/// Each provider a first account may be with, and the sign-in it leaves.
fn mail(out: &mut String, reach: &Reach) {
    out.push_str("### Mail\n\n");
    out.push_str(
        "One account at `init` (`--email` and `--mail-provider`); more are added to \
         `[[mail.accounts]]` later. Each provider leaves a sign-in only the person can do:\n\n",
    );
    for provider in Provider::value_variants() {
        let first = FirstAccount {
            provider: *provider,
            email: CAST.owner.email.to_owned(),
        };
        choice(out, provider);
        block(out, &first.steps(reach));
    }
}

/// The model every job runs, and the token it needs.
fn models(out: &mut String, reach: &Reach) {
    out.push_str("### Model\n\n");
    out.push_str(
        "Every job runs a Claude model through the `claude` CLI on the Claude subscription: \
         `[secretary] model` for the chat, the reviews and the titles, and `[secretary] \
         compactor` for the compactor. Its token is set at a terminal as below, or, once the app \
         runs, from the **Connect a model** card the box files in the Inbox whenever the model \
         does not answer.\n\n",
    );
    block(out, &super::onboarding::model_steps(reach));
}

/// The world a connector (a calendar, any other service) is written against.
fn connectors(out: &mut String) {
    out.push_str("### Calendars and other connectors\n\n");
    out.push_str(
        "A connector is a plugin: a WebAssembly component of the `source` world, built for \
         `wasm32-wasip2` and declared by a `[[plugins]]` table that names every origin it may \
         reach and every credential it may name. A credential is a secret link the host fetches \
         for it. The app ships the calendar (`ics`, one secret iCal link per calendar, each a \
         credential named `PLUGIN_ICS_<LABEL>`). The host links one import of its own, \
         `suzatary:plugin/fetch`, and of WASI only the clocks, random numbers and standard \
         streams.\n\n",
    );
}

/// One value of a flag's enum, as a list item: its spelling and its help.
fn choice(out: &mut String, value: &impl ValueEnum) {
    if let Some(value) = value.to_possible_value() {
        let help = value.get_help().map(|help| one_line(&help.to_string()));
        let _ = writeln!(
            out,
            "- `{}`: {}",
            value.get_name(),
            help.unwrap_or_default()
        );
    }
}

/// Steps as a console block indented under their list item; nothing for none.
fn block(out: &mut String, steps: &[super::Step]) {
    if steps.is_empty() {
        out.push('\n');
        return;
    }
    out.push_str("\n  ```console\n");
    for step in steps {
        let _ = writeln!(out, "  $ {}   # {}", step.command, step.why);
    }
    out.push_str("  ```\n\n");
}

/// Help text on one line, for a table cell or a list item.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}
