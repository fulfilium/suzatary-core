#!/usr/bin/env bash
# Install the official Proton Drive CLI as ~/bin/proton-drive (idempotent).
#
# Never patchelf it: it is a Bun single-file executable whose payload sits at fixed offsets. On
# NixOS it runs through a GC-rooted nix glibc loader instead.
set -euo pipefail

VER="${PROTON_DRIVE_CLI_VERSION:-0.8.0}"
case "$(uname -m)" in
  aarch64) ARCH=linux-arm64 ;;
  x86_64)  ARCH=linux-x64 ;;
  *) echo "install-proton-drive: unsupported arch $(uname -m)" >&2; exit 1 ;;
esac

mkdir -p "$HOME/bin"
if [ -x "$HOME/bin/proton-drive" ] && "$HOME/bin/proton-drive" --version >/dev/null 2>&1; then
  echo "install-proton-drive: already installed"
  exit 0
fi

curl -fsSL "https://proton.me/download/drive/cli/$VER/$ARCH/proton-drive" \
  -o "$HOME/bin/proton-drive.bin"
chmod +x "$HOME/bin/proton-drive.bin"

if "$HOME/bin/proton-drive.bin" --version >/dev/null 2>&1; then
  RUN="exec \"\$HOME/bin/proton-drive.bin\" \"\$@\""
else
  # NixOS has no /lib loader.
  nix build --out-link "$HOME/bin/.proton-drive-glibc" 'nixpkgs#glibc.out'
  LOADER=$(ls "$HOME"/bin/.proton-drive-glibc/lib/ld-linux-*.so.* | head -1)
  RUN="exec \"$LOADER\" \"\$HOME/bin/proton-drive.bin\" \"\$@\""
fi

cat > "$HOME/bin/proton-drive" <<WRAP
#!/usr/bin/env bash
# Generated by scripts/install-proton-drive.sh — do not patchelf the .bin.
# Sessions go to the pass store: no DBus secret-service on headless boxes.
export PROTON_DRIVE_CREDENTIALS_STORE=pass
$RUN
WRAP
chmod +x "$HOME/bin/proton-drive"
"$HOME/bin/proton-drive" --version
echo "install-proton-drive: installed to ~/bin/proton-drive"
