#!/usr/bin/env node
// Generates web/static/tokens.css and web/src/view/tokens.ts from tokens.typ, evaluated by
// typst, so no colour has a second definition. Run inside nix develop .#triage.
//
//   node scripts/gen-tokens.mjs          write both files
//   node scripts/gen-tokens.mjs --check  fail if either committed file is stale
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Each role as CSS hex; each fulfillment stop as OKLCH channels and its position.
const READ = `{
  import "/tokens.typ": tokens
  let hex(c) = rgb(c).to-hex()
  let lch(c) = {
    let (l, ch, h, ..) = oklch(c).components()
    (l: calc.round(l / 1%, digits: 2), c: calc.round(ch, digits: 4), h: calc.round(h / 1deg, digits: 2))
  }
  (
    light: tokens.light.pairs().map(((k, v)) => (k, hex(v))).to-dict(),
    dark: tokens.dark.pairs().map(((k, v)) => (k, hex(v))).to-dict(),
    fulfillment: tokens.fulfillment.stops().map(((c, at)) => (at: calc.round(at / 100%, digits: 4), colour: lch(c))),
  )
}`;

const tokens = JSON.parse(execFileSync("typst", ["eval", READ, "--root", root], { cwd: root, encoding: "utf8" }));

// Indented 2 spaces per depth.
const cssVars = (theme, depth) =>
  Object.entries(tokens[theme])
    .map(([name, value]) => `${"  ".repeat(depth)}--${name}: ${value};`)
    .join("\n");

const cssOklch = ({ l, c, h }) => `oklch(${l}% ${c} ${h})`;
const stops = tokens.fulfillment;

const tokensCss = `/* GENERATED by scripts/gen-tokens.mjs from tokens.typ, the app's colour roles
   as samples of the owner's design system (typst-design). Do not hand-edit;
   edit tokens.typ and re-run the generator. */

:root {
  --fulfillment-from: ${cssOklch(stops[0].colour)};
  --fulfillment-to: ${cssOklch(stops[stops.length - 1].colour)};
}

:root {
${cssVars("light", 1)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${cssVars("dark", 2)}
  }
}

:root[data-theme="dark"] {
${cssVars("dark", 1)}
}
`;

const tsStop = ({ at, colour: { l, c, h } }) => `    { at: ${at}, colour: { l: ${l}, c: ${c}, h: ${h} } },`;

const tokensTs = `// GENERATED by scripts/gen-tokens.mjs from tokens.typ. Do not hand-edit.

export namespace tokens {
  export type Oklch = { readonly l: number; readonly c: number; readonly h: number }
  export type Stop = { readonly at: number; readonly colour: Oklch }
  // The fulfillment scale's stops, at increasing positions from 0 to 1, the same in both themes.
  export const fulfillment: readonly [Stop, ...Stop[]] = [
${stops.map(tsStop).join("\n")}
  ]
}
export default tokens
`;

const outputs = {
  "web/static/tokens.css": tokensCss,
  "web/src/view/tokens.ts": tokensTs,
};

const readCurrent = (path) => {
  try {
    return readFileSync(join(root, path), "utf8");
  } catch {
    return null;
  }
};

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs)
    .filter(([path, content]) => readCurrent(path) !== content)
    .map(([path]) => path);
  if (stale.length > 0) {
    console.error(
      `gen-tokens.mjs --check: stale against tokens.typ: ${stale.join(", ")}\n` +
        "  run 'node scripts/gen-tokens.mjs' and commit the result",
    );
    process.exit(1);
  }
  console.log(`gen-tokens.mjs --check: ${Object.keys(outputs).join(", ")} match tokens.typ`);
  process.exit(0);
}

for (const [path, content] of Object.entries(outputs)) {
  writeFileSync(join(root, path), content);
  console.log(`wrote ${path}`);
}
